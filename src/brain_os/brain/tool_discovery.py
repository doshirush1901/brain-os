def is_low_confidence_response(response: str) -> bool:
    """Heuristic marker for low-confidence / unavailable results."""
    text = (response or "").lower()
    markers = (
        "not available",
        "i don't know",
        "i do not know",
        "unable to",
        "couldn't find",
        "cannot find",
        "insufficient",
        "not enough information",
        "uncertain",
    )
    return any(marker in text for marker in markers)
